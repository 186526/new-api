const (
	quotaRefundVersion = 1
	quotaDebitOpen     = "debited"
	quotaDebitSettled  = "settled"
)

var (
	quotaRefundSchemaReady     atomic.Bool
	ErrQuotaOperationDecided   = errors.New("quota operation already decided")
	ErrQuotaWalletInsufficient = errors.New("wallet quota insufficient")
	ErrQuotaTokenInsufficient  = errors.New("token quota insufficient")
)

// InitializeQuotaRefundRecovery is called after migration and configuration.
// Recovery of committed decisions does not enable the quota writers.
func InitializeQuotaRefundRecovery() bool {
	ready := DB != nil && DB.Migrator().HasColumn(&QuotaRefundReceipt{}, "Version") &&
		DB.Migrator().HasColumn(&QuotaRefundReceipt{}, "LogRequestID") &&
		DB.Migrator().HasColumn(&QuotaRefundReceipt{}, "Restored") &&
		DB.Migrator().HasColumn(&QuotaRefundReceipt{}, "RetryAt") &&
		DB.Migrator().HasColumn(&QuotaRefundReceipt{}, "Attempts")
	quotaRefundSchemaReady.Store(ready)
	return ready
}

// Local flags cannot establish that other processes no longer spend from the
// legacy ledger. Keep this off until all writers participate in the cutover.
const sqlQuotaLedgerWriterReady = false

func SQLQuotaLedgerWriterEnabled() bool {
	return sqlQuotaLedgerWriterReady && quotaRefundSchemaReady.Load() && !common.RedisEnabled && !common.BatchUpdateEnabled && !RegionEnabled()
}

// SQLQuotaDebit is a synchronous wallet reservation and its optional Token
// counterpart. ID is generated by the server; LogRequestID correlates logs only.
type SQLQuotaDebit struct {
	ID           string
	LogRequestID string
	Group        string
	UserID       int
	TokenID      int
}

// Reserve commits both debits and their evidence, or neither. target is the
// cumulative amount, so repeating a committed reservation does not debit again.
func (op SQLQuotaDebit) Reserve(target int, requireWalletBalance bool) error {
	if target <= 0 || target > common.MaxQuota || op.ID == "" || op.UserID <= 0 || op.TokenID < 0 {
		return errors.New("invalid SQL quota reservation")
	}
	return quotaSQLTransaction(DB, true, func(tx *gorm.DB) error {
		// A zero-amount row is only an internal lock anchor. It can never commit
		// independently of the debit below.
		wallet := op.receipt(RefundPartWallet, op.UserID, 0)
		if err := insertQuotaDebitAnchor(tx, wallet); err != nil {
			return err
		}
		if err := op.lockWallet(tx, &wallet); err != nil {
			return err
		}
		if wallet.Status != quotaDebitOpen {
			return ErrQuotaOperationDecided
		}
		if target < wallet.Quota {
			return ErrQuotaOperationDecided
		}
		delta := target - wallet.Quota
		if delta == 0 {
			return nil
		}
		if op.TokenID != 0 {
			if err := updateSQLDebitToken(tx, op.UserID, op.TokenID, delta, true); err != nil {
				return err
			}
			if wallet.Quota == 0 {
				item := op.receipt(RefundPartToken, op.TokenID, target)
				if err := tx.Select(quotaDebitReceiptColumns).Create(&item).Error; err != nil {
					return err
				}
			} else if err := op.debits(tx).Where("part = ?", RefundPartToken).Update("quota", target).Error; err != nil {
				return err
			}
		}
		if err := updateSQLDebitWallet(tx, op.UserID, delta, requireWalletBalance); err != nil {
			return err
		}
		return op.debits(tx).Where("part = ?", RefundPartWallet).Update("quota", target).Error
	})
}

var quotaDebitReceiptColumns = []string{"RequestID", "Part", "SubjectID", "Quota", "Group", "Version", "LogRequestID", "Status"}

func insertQuotaDebitAnchor(tx *gorm.DB, receipt QuotaRefundReceipt) error {
	return tx.Select(quotaDebitReceiptColumns).Clauses(clause.OnConflict{DoNothing: true}).Create(&receipt).Error
}

func (op SQLQuotaDebit) receipt(part string, subjectID, quota int) QuotaRefundReceipt {
	return QuotaRefundReceipt{RequestID: op.ID, Part: part, SubjectID: subjectID, Quota: quota,
		Group: op.Group, Version: quotaRefundVersion, LogRequestID: op.LogRequestID, Status: quotaDebitOpen}
}

func (op SQLQuotaDebit) debits(tx *gorm.DB) *gorm.DB {
	return tx.Model(&QuotaRefundReceipt{}).Where("request_id = ? AND version = ?", op.ID, quotaRefundVersion)
}

func (op SQLQuotaDebit) lockWallet(tx *gorm.DB, wallet *QuotaRefundReceipt) error {
	if err := op.debits(lockForUpdate(tx)).Where("part = ?", RefundPartWallet).Take(wallet).Error; err != nil {
		return err
	}
	if wallet.SubjectID != op.UserID || wallet.LogRequestID != op.LogRequestID || wallet.Group != op.Group {
		return errors.New("quota debit operation conflicts with stored identity")
	}
	token, err := op.readWalletTokenPart(tx, *wallet)
	if err != nil {
		return err
	}
	if wallet.Quota != 0 && token.SubjectID != op.TokenID {
		return errors.New("quota debit operation conflicts with stored token debit")
	}
	return nil
}

func (op SQLQuotaDebit) readWalletTokenPart(tx *gorm.DB, wallet QuotaRefundReceipt) (QuotaRefundReceipt, error) {
	var token QuotaRefundReceipt
	err := op.debits(tx).Where("part = ?", RefundPartToken).Take(&token).Error
	if errors.Is(err, gorm.ErrRecordNotFound) {
		return QuotaRefundReceipt{}, nil
	}
	if err != nil {
		return QuotaRefundReceipt{}, err
	}
	if wallet.Quota <= 0 || token.SubjectID <= 0 || token.Quota != wallet.Quota || token.Group != wallet.Group || token.LogRequestID != wallet.LogRequestID {
		return QuotaRefundReceipt{}, errors.New("invalid wallet token debit evidence")
	}
	return token, nil
}

func updateSQLDebitToken(tx *gorm.DB, userID, subjectID, delta int, requireAvailable bool) error {
	if delta == 0 {
		return nil
	}
	query := tx.Model(&Token{}).Where("id = ? AND user_id = ?", subjectID, userID).
		Where("remain_quota BETWEEN ? AND ? AND used_quota BETWEEN ? AND ?",
			-common.MaxWalletQuota+max(delta, 0), common.MaxWalletQuota+min(delta, 0),
			-common.MaxWalletQuota-min(delta, 0), common.MaxWalletQuota-max(delta, 0))
	if requireAvailable {
		query = query.Where("(unlimited_quota = ? OR remain_quota >= ?)", true, delta)
	}
	result := query.Updates(map[string]any{
		"remain_quota": gorm.Expr("remain_quota - ?", delta), "used_quota": gorm.Expr("used_quota + ?", delta),
		"accessed_time": common.GetTimestamp(),
	})
	if result.Error != nil {
		return result.Error
	}
	if result.RowsAffected != 1 {
		return ErrQuotaTokenInsufficient
	}
	return recordTokenBalance(tx, subjectID)
}

func updateSQLDebitWallet(tx *gorm.DB, subjectID, delta int, requireAvailable bool) error {
	if delta == 0 {
		return nil
	}
	query := tx.Model(&User{}).Where("id = ?", subjectID)
	if requireAvailable {
		query = query.Where("quota >= ?", delta)
	}
	query = query.Where("quota BETWEEN ? AND ?", -common.MaxWalletQuota+max(delta, 0), common.MaxWalletQuota+min(delta, 0))
	result := query.Update("quota", gorm.Expr("quota - ?", delta))
	if result.Error != nil {
		return result.Error
	}
	if result.RowsAffected != 1 {
		return ErrQuotaWalletInsufficient
	}
	return recordWalletBalance(tx, subjectID)
}

// Settle atomically commits the final adjustment and bars refund decisions.
func (op SQLQuotaDebit) Settle(actual int) error {
	if actual < 0 || actual > common.MaxQuota {
		return errors.New("invalid quota settlement amount")
	}
	return quotaSQLTransaction(DB, false, func(tx *gorm.DB) error {
		var wallet QuotaRefundReceipt
		if err := op.lockWallet(tx, &wallet); err != nil {
			return err
		}
		if wallet.Status == quotaDebitSettled {
			if wallet.RestoreReason != "settled" || actual != wallet.SettlementQuota {
				return ErrQuotaOperationDecided
			}
			return nil
		}
		if wallet.Status != quotaDebitOpen || wallet.Quota <= 0 || wallet.Quota > common.MaxQuota {
			return ErrQuotaOperationDecided
		}
		delta := actual - wallet.Quota
		if op.TokenID != 0 {
			if err := updateSQLDebitToken(tx, op.UserID, op.TokenID, delta, false); err != nil {
				return err
			}
		}
		if err := updateSQLDebitWallet(tx, op.UserID, delta, false); err != nil {
			return err
		}
		return op.updateOpenParts(tx, settlementFields(actual, delta, delta, "settled"))
	})
}

// DecideRefund is the point after which another process can safely retry. A
// debit without a terminal decision stays visible for reconciliation and is not
// automatically refunded when a process dies.
func (op SQLQuotaDebit) DecideRefund() error {
	return quotaSQLTransaction(DB, false, func(tx *gorm.DB) error {
		var wallet QuotaRefundReceipt
		if err := op.lockWallet(tx, &wallet); err != nil {
			return err
		}
		switch wallet.Status {
		case RefundRequested, RefundCompleted, RefundFailed:
			return nil
		case quotaDebitOpen:
			if wallet.Quota <= 0 || wallet.Quota > common.MaxQuota {
				return ErrQuotaOperationDecided
			}
		default:
			return ErrQuotaOperationDecided
		}
		return op.updateOpenParts(tx, map[string]any{
			"status": RefundRequested, "requested_at": common.GetTimestamp(),
		})
	})
}

func (op SQLQuotaDebit) updateOpenParts(tx *gorm.DB, fields map[string]any) error {
	parts := []string{RefundPartWallet}
	if op.TokenID != 0 {
		parts = append(parts, RefundPartToken)
	}
	result := op.debits(tx).Where("part IN ? AND status = ?", parts, quotaDebitOpen).Updates(fields)
	if result.Error != nil {
		return result.Error
	}
	if result.RowsAffected != int64(len(parts)) {
		return ErrQuotaOperationDecided
	}
	return nil
}

// ApplyRefund applies only a committed decision. The credit and status update
// share a transaction, so concurrent requests and restart recovery cannot pay
// the same part twice.
func (op SQLQuotaDebit) ApplyRefund(ctx context.Context) (string, error) {
	if op.UserID <= 0 {
		return RefundRequested, errors.New("invalid wallet refund owner")
	}
	return op.applyRefund(ctx, true)
}

func applyCommittedQuotaRefund(ctx context.Context, operationID string) (string, error) {
	return (SQLQuotaDebit{ID: operationID}).applyRefund(ctx, false)
}

func (op SQLQuotaDebit) applyRefund(ctx context.Context, checkIdentity bool) (string, error) {
	outcome := RefundRequested
	err := quotaSQLTransaction(DB.WithContext(ctx), false, func(tx *gorm.DB) error {
		var wallet QuotaRefundReceipt
		if checkIdentity {
			if err := op.lockWallet(tx, &wallet); err != nil {
				return err
			}
		} else if err := op.debits(lockForUpdate(tx)).Where("part = ?", RefundPartWallet).Take(&wallet).Error; err != nil {
			return err
		}
		if wallet.Status != RefundRequested && wallet.Status != RefundCompleted && wallet.Status != RefundFailed {
			return ErrQuotaOperationDecided
		}
		token, err := op.readWalletTokenPart(tx, wallet)
		if err != nil {
			return err
		}
		outcome = RefundCompleted
		for _, part := range []QuotaRefundReceipt{token, wallet} {
			if part.Part == "" {
				continue
			}
			switch part.Status {
			case RefundRequested:
				status, err := applyCommittedQuotaPart(tx, wallet, part)
				if err != nil {
					return err
				}
				if status == RefundFailed {
					outcome = RefundFailed
				}
			case RefundFailed:
				outcome = RefundFailed
			case RefundCompleted:
			default:
				return ErrQuotaOperationDecided
			}
		}
		return nil
	})
	if err != nil {
		return RefundRequested, err
	}
	return outcome, nil
}

func applyCommittedQuotaPart(tx *gorm.DB, wallet, part QuotaRefundReceipt) (string, error) {
	if part.Quota <= 0 || part.Quota > common.MaxQuota {
		return RefundRequested, fmt.Errorf("invalid committed quota %d", part.Quota)
	}
	var err error
	switch part.Part {
	case RefundPartWallet:
		err = updateSQLDebitWallet(tx, wallet.SubjectID, -part.Quota, false)
	case RefundPartToken:
		err = updateSQLDebitToken(tx, wallet.SubjectID, part.SubjectID, -part.Quota, false)
	default:
		return RefundRequested, errors.New("unknown wallet refund part")
	}
	status, restored, reason := RefundCompleted, part.Quota, "restored"
	if errors.Is(err, ErrQuotaWalletInsufficient) || errors.Is(err, ErrQuotaTokenInsufficient) {
		status, restored, reason = RefundFailed, 0, "subject_not_creditable"
	} else if err != nil {
		return RefundRequested, err
	}
	result := quotaRefundSelection(tx, part).Where("version = ? AND status = ?", quotaRefundVersion, RefundRequested).
		Updates(map[string]any{"status": status, "restored": restored, "restore_reason": reason})
	if result.Error != nil {
		return RefundRequested, result.Error
	}
	if result.RowsAffected != 1 {
		return RefundRequested, errors.New("refund credit has no matching receipt update")
	}
	return status, nil
}

// RecoverQuotaRefunds handles a bounded set of committed decisions. Old
// receipts remain observation only; they have no trustworthy debit evidence.
func RecoverQuotaRefunds(ctx context.Context) error {
	var entries []QuotaRefundReceipt
	query := DB.WithContext(ctx).Where("((version = ? AND part = ?) OR (version IN ? AND part = ?)) AND status = ? AND retry_at <= ?",
		quotaRefundVersion, RefundPartWallet, []int{subscriptionRefundVersion, subscriptionTokenRefundVersion}, RefundPartSubscription, RefundRequested, common.GetTimestamp())
	if err := query.Order("retry_at ASC, requested_at ASC, request_id ASC").Limit(32).Find(&entries).Error; err != nil {
		return err
	}
	var firstError error
	for _, entry := range entries {
		if ctx.Err() != nil {
			return ctx.Err()
		}
		applyCtx, cancel := context.WithTimeout(ctx, 3*time.Second)
		var err error
		switch entry.Version {
		case subscriptionTokenRefundVersion:
			_, err = applySubscriptionTokenRefund(applyCtx, entry.RequestID)
		case subscriptionRefundVersion:
			err = applyCommittedSubscriptionRefund(applyCtx, entry.RequestID)
		default:
			_, err = applyCommittedQuotaRefund(applyCtx, entry.RequestID)
		}
		cancel()
		if err == nil {
			continue
		}
		delay := int64(1 << min(entry.Attempts+1, 8))
		retryErr := quotaRefundSelection(DB.WithContext(ctx), entry).
			Where("version = ? AND status = ? AND attempts = ?", entry.Version, RefundRequested, entry.Attempts).
			Updates(map[string]any{"attempts": entry.Attempts + 1, "retry_at": common.GetTimestamp() + delay}).Error
		if firstError == nil {
			firstError = errors.Join(err, retryErr)
		}
	}
	return firstError
}
